# =========================================================
# تحويل قاعدة المعرفة إلى نص
# =========================================================

def build_knowledge_text() -> str:

    sections = []

    for item in KNOWLEDGE:

        title = item.get(
            "title",
            "معلومة"
        )

        keywords = item.get(
            "keywords",
            []
        )

        answer = item.get(
            "answer",
            ""
        )

        section = (
            f"العنوان: {title}\n"
            f"الكلمات المرتبطة: "
            f"{', '.join(keywords)}\n"
            f"المعلومة: {answer}"
        )

        sections.append(
            section
        )

    return "\n\n".join(
        sections
    )


# =========================================================
# البحث المباشر في قاعدة المعرفة
# =========================================================

def search_knowledge(
    query: str
):

    if not query:
        return []

    query = query.lower()

    results = []

    for item in KNOWLEDGE:

        score = 0

        for keyword in item.get(
            "keywords",
            []
        ):

            if keyword.lower() in query:

                score += 1

        if score > 0:

            results.append(
                (
                    score,
                    item
                )
            )

    # الأعلى تطابقًا أولًا
    results.sort(
        key=lambda x: x[0],
        reverse=True
    )

    return [
        item
        for score, item in results
    ]


