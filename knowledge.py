# =========================================================
# تنظيف السؤال
# =========================================================

def normalize_text(
    text: str
) -> str:

    if not text:
        return ""

    text = text.lower().strip()

    text = (
        text
        .replace("أ", "ا")
        .replace("إ", "ا")
        .replace("آ", "ا")
    )

    return text


# =========================================================
# هل السؤال متعلق بالمنصة؟
# =========================================================

def is_platform_question(
    text: str
) -> bool:

    text = normalize_text(
        text
    )

    if not text:
        return False

    # ذكر Crynova مباشرة
    if (
        "crynova" in text
        or "كرينوفا" in text
    ):
        return True

    # البحث عن كلمات المنصة
    for keyword in PLATFORM_KEYWORDS:

        if normalize_text(
            keyword
        ) in text:

            return True

    return False


# =========================================================
# البحث عن سؤال مشابه
# =========================================================

def search_knowledge(
    query: str,
    limit: int = 5
):

    query = normalize_text(
        query
    )

    if not query:
        return []

    results = []

    for item in FAQ:

        score = 0

        # -------------------------------------------------
        # الكلمات المفتاحية
        # -------------------------------------------------

        for keyword in item.get(
            "keywords",
            []
        ):

            keyword = normalize_text(
                keyword
            )

            if keyword in query:

                score += 3

        # -------------------------------------------------
        # كلمات السؤال
        # -------------------------------------------------

        question = normalize_text(
            item.get(
                "question",
                ""
            )
        )

        for word in question.split():

            if len(word) >= 3 and word in query:

                score += 1

        if score > 0:

            results.append(
                (
                    score,
                    item
                )
            )

    # الأعلى تطابقًا أولًا
    results.sort(
        key=lambda item: item[0],
        reverse=True
    )

    return [
        item
        for score, item in results[:limit]
    ]


# =========================================================
# الحصول على إجابة مباشرة
# =========================================================

def get_best_answer(
    query: str
) -> Optional[str]:

    results = search_knowledge(
        query,
        limit=1
    )

    if not results:
        return None

    return results[0].get(
        "answer"
    )


