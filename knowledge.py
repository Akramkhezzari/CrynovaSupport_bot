def build_knowledge_text() -> str:

    sections = []

    sections.append(
        "اسم المنصة: "
        + PLATFORM_INFO["name"]
    )

    sections.append(
        "وصف المنصة: "
        + PLATFORM_INFO["description"]
    )

    sections.append(
        "\nالأقسام المتوفرة:"
    )

    for key, section in SECTIONS.items():

        sections.append(
            f"- {section['name']}: "
            f"{section['description']}"
        )

    sections.append(
        "\nالأسئلة والأجوبة الرسمية:"
    )

    for item in FAQ:

        sections.append(
            "\n"
            f"ID: {item['id']}\n"
            f"القسم: {item['category']}\n"
            f"السؤال: {item['question']}\n"
            f"الإجابة: {item['answer']}"
        )

    return "\n".join(
        sections
    )


